// Glyphe d'un caractère (espace si absent).
export function glyph(ch: string): Glyph {
  return G[ch] ?? G[" "]!;
}

// Largeur d'une chaîne en colonnes de dots (sans la dessiner). Tout glyphe (présent
// ou espace de repli) occupe GLYPH_W ; on additionne les GLYPH_GAP intermédiaires.
export function textCols(text: string): number {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP;
}
